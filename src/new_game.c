void NewGameInitData(void)
{
#if IS_FRLG
    u8 rivalName[PLAYER_NAME_LENGTH + 1];
#endif
    if (gSaveFileStatus == SAVE_STATUS_EMPTY || gSaveFileStatus == SAVE_STATUS_CORRUPT)
        RtcReset();

#if IS_FRLG
    StringCopy(rivalName, gSaveBlock1Ptr->rivalName);
#endif
    gDifferentSaveFile = TRUE;
    gSaveBlock2Ptr->encryptionKey = 0;
    ZeroPlayerPartyMons();
    ZeroEnemyPartyMons();
    ResetPokedex();
    ClearFrontierRecord();
    ClearSav1();
    ClearSav3();
    ClearAllMail();
    gSaveBlock2Ptr->specialSaveWarpFlags = 0;
    gSaveBlock2Ptr->gcnLinkFlags = 0;
    InitPlayerTrainerId();
    PlayTimeCounter_Reset();
    ClearPokedexFlags();
    InitEventData();
    ClearTVShowData();
    ResetGabbyAndTy();
    ClearSecretBases();
    ClearBerryTrees();
    SetMoney(&gSaveBlock1Ptr->money, 3000);
    SetCoins(0);
    ResetLinkContestBoolean();
    ResetGameStats();
    ClearAllContestWinnerPics();
    ClearPlayerLinkBattleRecords();
    InitSeedotSizeRecord();
    InitLotadSizeRecord();
    gPartiesCount[B_TRAINER_PLAYER] = 0;
    ZeroPlayerPartyMons();
    ResetPokemonStorageSystem();
    DeactivateAllRoamers();
    gSaveBlock1Ptr->registeredItem = ITEM_NONE;
    ClearBag();
    NewGameInitPCItems();
    ClearPokeblocks();
    ClearDecorationInventories();
    InitEasyChatPhrases();
    SetMauvilleOldMan();
    InitDewfordTrend();
    ResetFanClub();
    ResetLotteryCorner();
    UpdateDailySeed();
    WarpToTruck();
    // Pokemon Anime Edition: clear both Hoenn and Kanto map flags so the
    // combined Hoenn + Kanto build starts with a clean state.
    RunScriptImmediately(EventScript_ResetAllMapFlags);
    RunScriptImmediately(EventScript_ResetAllMapFlagsFrlg);
    // Pokemon Anime Edition: persist the boot selections (language from
    // the boot menus, gender / name from the Oak intro). This runs after
    // Sav2_ClearSetDefault() and after both map flag resets above, which
    // clear gSaveBlock2Ptr and all flags.
    gSaveBlock2Ptr->playerGender = gSelectedBootGender;
    StringCopy(gSaveBlock2Ptr->playerName, gSelectedBootName);
    SetAnimeLanguage(gSelectedBootLanguage);
#if IS_FRLG
    StringCopy(gSaveBlock1Ptr->rivalName, rivalName);
#endif
    // The rival is always GARY: ClearSav1() above wipes the name and the
    // Oak intro skips the rival naming screen.
    StringCopy(gSaveBlock1Ptr->rivalName, sText_AnimeRivalDefaultName);
    // Pokemon Anime Edition (anime opening): by the time the player arrives,
    // the other trainers already took Bulbasaur/Squirtle/Charmander and the
    // rival has left. Hide those leftovers inside Oak's lab and keep Oak out
    // of the street (he waits in his lab). The town's Oak trigger is disabled
    // through its map-scene var so the vanilla 3-starter scene never starts.
    // Anime opening: the other trainers already took Bulbasaur/Squirtle/
    // Charmander and the rival has left, so hide those leftovers in the lab
    // and keep Oak inside his lab.
    FlagSet(FLAG_HIDE_BULBASAUR_BALL);
    FlagSet(FLAG_HIDE_SQUIRTLE_BALL);
    FlagSet(FLAG_HIDE_CHARMANDER_BALL);
    FlagSet(FLAG_HIDE_RIVAL_IN_LAB);
    FlagSet(FLAG_HIDE_OAK_IN_PALLET_TOWN);
    VarSet(VAR_MAP_SCENE_PALLET_TOWN_OAK, 1);
    ResetMiniGamesRecords();
    InitUnionRoomChatRegisteredTexts();
    InitLilycoveLady();
    ResetAllApprenticeData();
    ClearRankingHallRecords();
    InitMatchCallCounters();
    ClearMysteryGift();
    WipeTrainerNameRecords();
    ResetTrainerHillResults();
    ResetTrainerTowerResults();
    ResetContestLinkResults();
    SetCurrentDifficultyLevel(DIFFICULTY_NORMAL);
    ResetItemFlags();
    ResetDexNav();
    ClearFollowerNPCData();
}

